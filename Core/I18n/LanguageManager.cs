        public static string Get(string key)
        {
            if (Translations.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(key, out string? val))
            {
                return val;
            }
            if (Translations.TryGetValue("TR", out var trDict) && trDict.TryGetValue(key, out string? trVal))
            {
                return trVal;
